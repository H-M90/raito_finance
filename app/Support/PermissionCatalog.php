    public static function permissions(): array
    {
        $permissions = [];
        foreach (self::groups() as $groupCode => $group) {
            foreach ($group['permissions'] as $code => $definition) {
                $permissions[$code] = [
                    'name' => $definition[0],
                    'description' => $definition[1] ?? null,
                    'group' => $groupCode,
                    'group_label' => $group['label'],
                ];
            }
        }
        return $permissions;
    }

    public static function name(string $code): string
    {
        return self::permissions()[$code]['name'] ?? $code;
    }

    public static function description(string $code): ?string
    {
        return self::permissions()[$code]['description'] ?? null;
    }

    public static function groupLabel(string $group): string
    {
        return self::groups()[$group]['label'] ?? $group;
    }

    public static function groupDescription(string $group): ?string
    {
        return self::groups()[$group]['description'] ?? null;
    }

    public static function groupOrder(): array
    {
        return array_keys(self::groups());
    }
